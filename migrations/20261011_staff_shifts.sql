-- Employee weekly shift assignments.
-- Apply ONLY to the isolated test database until production approval.
CREATE TABLE IF NOT EXISTS staff_shifts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id INTEGER NOT NULL REFERENCES staff_users(id) ON DELETE CASCADE,
  weekday INTEGER NOT NULL CHECK (weekday BETWEEN 0 AND 6),
  start_time TIME,
  end_time TIME,
  is_off BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT staff_shifts_unique_day UNIQUE (staff_id, weekday),
  CONSTRAINT staff_shifts_valid_time CHECK (
    (is_off = TRUE AND start_time IS NULL AND end_time IS NULL)
    OR
    (is_off = FALSE AND start_time IS NOT NULL AND end_time IS NOT NULL)
  )
);
