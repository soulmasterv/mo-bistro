-- Administrator-only repair. Verify isolation before applying; no data is deleted.
BEGIN;

ALTER TABLE public.staff_users
  ADD COLUMN IF NOT EXISTS pin_hash TEXT;

ALTER TABLE public.staff_users
  DROP CONSTRAINT IF EXISTS staff_users_role_check;

ALTER TABLE public.staff_users
  ADD CONSTRAINT staff_users_role_check
  CHECK (role IN ('manager', 'reception', 'waiter'));


-- Employee weekly shift assignments.
-- Apply ONLY to the isolated test database until production approval.
CREATE TABLE IF NOT EXISTS staff_shifts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id INTEGER NOT NULL REFERENCES staff_users(id) ON DELETE CASCADE,
  weekday INTEGER NOT NULL CHECK (weekday BETWEEN 0 AND 6),
  start_time TIME,
  end_time TIME,
  is_off BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT staff_shifts_unique_day UNIQUE (staff_id, weekday),
  CONSTRAINT staff_shifts_valid_time CHECK (
    (is_off = TRUE AND start_time IS NULL AND end_time IS NULL)
    OR
    (is_off = FALSE AND start_time IS NOT NULL AND end_time IS NOT NULL)
  )
);

ALTER TABLE public.staff_shifts ADD COLUMN IF NOT EXISTS staff_id INTEGER REFERENCES public.staff_users(id) ON DELETE CASCADE;
ALTER TABLE public.staff_shifts ADD COLUMN IF NOT EXISTS weekday INTEGER;
ALTER TABLE public.staff_shifts ADD COLUMN IF NOT EXISTS start_time TIME;
ALTER TABLE public.staff_shifts ADD COLUMN IF NOT EXISTS end_time TIME;
ALTER TABLE public.staff_shifts ADD COLUMN IF NOT EXISTS is_off BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE public.staff_shifts ALTER COLUMN start_time TYPE TIME USING NULLIF(start_time::text,'')::time;
ALTER TABLE public.staff_shifts ALTER COLUMN end_time TYPE TIME USING NULLIF(end_time::text,'')::time;
ALTER TABLE public.staff_shifts ALTER COLUMN staff_id SET NOT NULL;
ALTER TABLE public.staff_shifts ALTER COLUMN weekday SET NOT NULL;
ALTER TABLE public.staff_shifts DROP CONSTRAINT IF EXISTS staff_shifts_valid_time;
ALTER TABLE public.staff_shifts ADD CONSTRAINT staff_shifts_valid_time CHECK (
  (is_off AND start_time IS NULL AND end_time IS NULL) OR
  (NOT is_off AND start_time IS NOT NULL AND end_time IS NOT NULL)
);

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.staff_shifts'::regclass AND conname='staff_shifts_unique_day') THEN
    ALTER TABLE public.staff_shifts ADD CONSTRAINT staff_shifts_unique_day UNIQUE(staff_id,weekday);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.staff_shifts'::regclass AND conname='staff_shifts_staff_id_fkey') THEN
    ALTER TABLE public.staff_shifts ADD CONSTRAINT staff_shifts_staff_id_fkey FOREIGN KEY(staff_id) REFERENCES public.staff_users(id) ON DELETE CASCADE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.staff_shifts'::regclass AND conname='staff_shifts_weekday_check') THEN
    ALTER TABLE public.staff_shifts ADD CONSTRAINT staff_shifts_weekday_check CHECK (weekday BETWEEN 0 AND 6);
  END IF;
END $$;
COMMIT;
