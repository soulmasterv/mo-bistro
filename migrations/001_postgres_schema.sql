BEGIN;

CREATE TABLE IF NOT EXISTS staff_users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('manager', 'reception')),
  credential_hash TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS staff_users_username_ci
  ON staff_users (LOWER(username));

CREATE TABLE IF NOT EXISTS staff_sessions (
  id_hash TEXT PRIMARY KEY,
  staff_id INTEGER NOT NULL REFERENCES staff_users(id),
  expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS staff_login_attempts (
  username_hash TEXT PRIMARY KEY,
  failures INTEGER NOT NULL DEFAULT 0,
  locked_until BIGINT NOT NULL DEFAULT 0,
  updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS guests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  party_size INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'waiting',
  confirmed INTEGER NOT NULL DEFAULT 0,
  source TEXT NOT NULL DEFAULT 'staff',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  tracking_token_hash TEXT,
  seating_preference TEXT NOT NULL DEFAULT 'any'
    CHECK (seating_preference IN ('indoor', 'outdoor', 'any')),
  table_id INTEGER
);

CREATE INDEX IF NOT EXISTS idx_guests_queue
  ON guests(status, created_at, id);

CREATE UNIQUE INDEX IF NOT EXISTS idx_guests_tracking_token
  ON guests(tracking_token_hash);

CREATE UNIQUE INDEX IF NOT EXISTS one_active_guest_per_table
  ON guests(table_id)
  WHERE table_id IS NOT NULL AND status = 'seated';

CREATE TABLE IF NOT EXISTS restaurant_tables (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  seats INTEGER NOT NULL CHECK (seats BETWEEN 1 AND 30),
  status TEXT NOT NULL DEFAULT 'free'
    CHECK (status IN ('free', 'occupied')),
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  area TEXT NOT NULL DEFAULT 'indoor'
    CHECK (area IN ('indoor', 'outdoor'))
);

CREATE UNIQUE INDEX IF NOT EXISTS restaurant_tables_name_ci
  ON restaurant_tables (LOWER(name));

CREATE TABLE IF NOT EXISTS seating_history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guest_id INTEGER NOT NULL,
  table_id INTEGER NOT NULL,
  assigned_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  released_at TEXT
);

CREATE TABLE IF NOT EXISTS restaurant_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS seating_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS booking_recovery_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  query_hash TEXT NOT NULL,
  created_at BIGINT NOT NULL
);

COMMIT;
