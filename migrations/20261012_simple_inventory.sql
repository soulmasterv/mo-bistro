-- Review and apply only to an independently verified isolated database.
-- Anonymous capacity is separate from restaurant_tables and seating_history.
BEGIN;
CREATE TABLE IF NOT EXISTS public.simple_table_capacity (
  area TEXT PRIMARY KEY CHECK (area IN ('indoor','outdoor')),
  total_tables INTEGER NOT NULL CHECK (total_tables BETWEEN 0 AND 500),
  occupied_tables INTEGER NOT NULL DEFAULT 0,
  max_party_size INTEGER NOT NULL CHECK (max_party_size BETWEEN 1 AND 30),
  CHECK (occupied_tables BETWEEN 0 AND total_tables)
);
INSERT INTO public.simple_table_capacity(area,total_tables,max_party_size)
SELECT a.area, COUNT(t.id)::integer, COALESCE(MIN(t.seats),4)
FROM (VALUES ('indoor'),('outdoor')) a(area)
LEFT JOIN public.restaurant_tables t ON LOWER(t.area)=a.area
GROUP BY a.area ON CONFLICT (area) DO NOTHING;
CREATE TABLE IF NOT EXISTS public.simple_table_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operation_id TEXT NOT NULL UNIQUE,
  area TEXT NOT NULL REFERENCES public.simple_table_capacity(area),
  kind TEXT NOT NULL CHECK (kind IN ('occupied','released')),
  actor_id INTEGER NOT NULL REFERENCES public.staff_users(id),
  guest_id INTEGER REFERENCES public.guests(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE public.table_ready_requests ADD COLUMN IF NOT EXISTS inventory_mode TEXT NOT NULL DEFAULT 'detailed';
ALTER TABLE public.table_ready_requests DROP CONSTRAINT IF EXISTS table_ready_requests_inventory_mode_check;
ALTER TABLE public.table_ready_requests ADD CONSTRAINT table_ready_requests_inventory_mode_check
  CHECK (inventory_mode IN ('simple','detailed') AND
    (inventory_mode <> 'simple' OR (table_id IS NULL AND area IS NOT NULL)));
COMMIT;
